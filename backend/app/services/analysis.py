"""Evidence-grounded contract risk analysis, document comparison and summarisation.

Every LLM call receives numbered source passages; every factual item it returns must cite
[S#] ids which are validated against the retrieved chunks. Items without valid evidence
are dropped (or explicitly flagged), so nothing shown to the user is unsupported."""
from __future__ import annotations

import time
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import Document, DocumentChunk
from app.services.citations import Source, validate_source_ids, verify_quote
from app.services.hybrid import retrieve
from app.services.llm import get_llm, parse_json
from app.services.retrieval_types import RetrievedChunk

DISCLAIMER = (
    "This analysis is generated by AI from the uploaded document for informational purposes only. "
    "It is not legal advice; consult a qualified lawyer before acting on it."
)

RISK_CATEGORIES: list[tuple[str, str, str]] = [
    ("termination", "Termination", "termination terminate notice period for convenience breach cure period expiry"),
    ("payment", "Payment terms", "payment fees invoice due days late payment interest price"),
    ("liability", "Liability", "limitation of liability liable damages cap consequential indirect loss"),
    ("confidentiality", "Confidentiality", "confidential information non-disclosure disclose secrecy"),
    ("indemnification", "Indemnification", "indemnify indemnification hold harmless defend claims"),
    ("dispute_resolution", "Dispute resolution", "dispute arbitration governing law jurisdiction courts mediation"),
    ("duration", "Contract duration", "term duration commencement effective date renewal automatically renew"),
    ("responsibilities", "Responsibilities", "obligations responsibilities shall provide perform services deliverables"),
    ("penalties", "Penalty clauses", "penalty liquidated damages service credits fine late delivery"),
]

COMPARE_ASPECTS: list[tuple[str, str]] = [
    ("Parties involved", "parties agreement between company client provider entered into"),
    ("Payment conditions", "payment fees invoice due days late payment interest"),
    ("Termination clauses", "termination terminate notice period for convenience breach"),
    ("Liability", "limitation of liability liable damages cap consequential"),
    ("Confidentiality", "confidential information non-disclosure disclose"),
    ("Contract duration", "term duration effective date renewal renew"),
    ("Dispute resolution", "dispute arbitration governing law jurisdiction courts"),
    ("Responsibilities", "obligations responsibilities shall provide perform services"),
    ("Penalties", "penalty liquidated damages service credits late"),
]

SUMMARY_ASPECTS = [
    "parties agreement between entered into by and between",
    "obligations shall provide perform responsibilities",
    "payment fees price invoice amount",
    "effective date term commencement deadline days",
    "termination terminate notice",
    "liability indemnify damages",
    "confidential information non-disclosure",
    "risk penalty breach",
]

ANALYST_SYSTEM = (
    "You are LegalMind AI, a careful contract analyst. You only use the numbered source passages "
    "provided. Never invent clauses, numbers, dates, parties or page numbers. Every finding must "
    "cite the supporting source ids (e.g. \"S3\"). Do not declare any clause illegal or "
    "unenforceable; describe potential risks neutrally. Respond with valid JSON only."
)


# --------------------------------------------------------------------------- helpers
def _doc_sources(
    db: Session, user_id: str, doc: Document, queries: list[str], per_query: int, start_id: int = 1
) -> list[Source]:
    """Retrieve the best passages of one document for several aspect queries."""
    seen: set[str] = set()
    sources: list[Source] = []
    for q in queries:
        res = retrieve(db, user_id, q, mode="hybrid", document_ids=[doc.id], top_k=12, rerank_top_n=per_query)
        for c in res.chunks:
            if c.chunk_id in seen:
                continue
            seen.add(c.chunk_id)
            sources.append(Source(start_id + len(sources), c))
    return sources


def _all_chunks(db: Session, user_id: str, doc: Document) -> list[RetrievedChunk]:
    rows = db.scalars(
        select(DocumentChunk)
        .where(DocumentChunk.document_id == doc.id, DocumentChunk.user_id == user_id)
        .order_by(DocumentChunk.chunk_index)
    ).all()
    return [
        RetrievedChunk(
            chunk_id=r.id, document_id=r.document_id, document_name=r.document_name,
            page_number=r.page_number, text=r.chunk_text, chunk_index=r.chunk_index,
        )
        for r in rows
    ]


def _format_sources(sources: list[Source], label: dict[str, str] | None = None, max_chars: int = 30000) -> str:
    parts, used = [], 0
    for s in sources:
        tag = f" | {label[s.chunk.document_id]}" if label else ""
        block = f"[S{s.source_id}]{tag} | {s.chunk.document_name} | Page {s.chunk.page_number}\n{s.chunk.text.strip()}\n"
        if used + len(block) > max_chars:
            break
        parts.append(block)
        used += len(block)
    return "\n".join(parts)


def _ids(item: dict) -> list:
    v = item.get("source_ids") or item.get("sources") or []
    return v if isinstance(v, list) else [v]


def _level(v: Any) -> str:
    v = str(v or "").upper()
    return v if v in {"LOW", "MEDIUM", "HIGH"} else "MEDIUM"


def _num(raw: Any) -> int | None:
    import re

    m = re.search(r"\d+", str(raw))
    return int(m.group()) if m else None


# --------------------------------------------------------------------------- risk analysis
def contract_risk(db: Session, user_id: str, doc: Document) -> dict:
    t0 = time.perf_counter()
    sources = _doc_sources(db, user_id, doc, [q for _, _, q in RISK_CATEGORIES], per_query=3)
    if not sources:
        raise ValueError("No indexed text found for this document.")
    cats = ", ".join(f"{key} ({name})" for key, name, _ in RISK_CATEGORIES)
    prompt = f"""Review the contract passages below and identify potential risks for the categories: {cats}.

SOURCE PASSAGES:
{_format_sources(sources)}

Return JSON with exactly this shape:
{{
  "overall_risk": "LOW" | "MEDIUM" | "HIGH",
  "overview": "2-4 sentence neutral overview of the contract's risk profile",
  "findings": [
    {{
      "category": "one of the category keys",
      "clause_name": "short clause title",
      "extracted_text": "verbatim quote (max ~60 words) copied exactly from the cited source",
      "potential_risk": "one-line description of the potential risk",
      "explanation": "why this may be risky and for which party, 2-3 sentences",
      "risk_level": "LOW" | "MEDIUM" | "HIGH",
      "source_ids": ["S1"]
    }}
  ],
  "missing_clauses": [{{"category": "category key", "note": "what appears to be absent from the passages"}}]
}}
Rules: one finding per distinct clause (several per category allowed); a category with no relevant
passage goes in missing_clauses (say "not found in retrieved passages", never claim it is absent from
the whole contract with certainty); extracted_text must be copied from the cited source."""
    data = parse_json(get_llm().generate(prompt, system=ANALYST_SYSTEM, json_mode=True))
    findings = []
    dropped = 0
    valid_keys = {k for k, _, _ in RISK_CATEGORIES}
    for f in data.get("findings", []) or []:
        if not isinstance(f, dict):
            continue
        cites = validate_source_ids(_ids(f), sources)
        if not cites:
            dropped += 1
            continue
        quote, verified = verify_quote(str(f.get("extracted_text", "")), sources, [c["source_id"] for c in cites])
        cat = str(f.get("category", "")).lower().strip()
        findings.append(
            {
                "category": cat if cat in valid_keys else "other",
                "clause_name": str(f.get("clause_name") or "Clause").strip(),
                "extracted_text": quote,
                "quote_verified": verified,
                "potential_risk": str(f.get("potential_risk") or "").strip(),
                "explanation": str(f.get("explanation") or "").strip(),
                "risk_level": _level(f.get("risk_level")),
                "document_name": doc.filename,
                "page_number": cites[0]["page_number"],
                "citations": cites,
            }
        )
    order = {"HIGH": 0, "MEDIUM": 1, "LOW": 2}
    findings.sort(key=lambda f: order[f["risk_level"]])
    counts = {lvl: sum(1 for f in findings if f["risk_level"] == lvl) for lvl in ("HIGH", "MEDIUM", "LOW")}
    missing = [
        {"category": str(m.get("category", "")), "note": str(m.get("note", ""))}
        for m in (data.get("missing_clauses") or [])
        if isinstance(m, dict)
    ]
    return {
        "document_id": doc.id,
        "document_name": doc.filename,
        "overall_risk": _level(data.get("overall_risk")) if findings else "LOW",
        "overview": str(data.get("overview") or ""),
        "counts": counts,
        "findings": findings,
        "missing_clauses": missing,
        "categories": [{"key": k, "name": n} for k, n, _ in RISK_CATEGORIES],
        "unsupported_findings_removed": dropped,
        "sources_reviewed": len(sources),
        "duration_ms": int((time.perf_counter() - t0) * 1000),
        "disclaimer": DISCLAIMER,
    }


# --------------------------------------------------------------------------- comparison
def compare_documents(db: Session, user_id: str, doc_a: Document, doc_b: Document) -> dict:
    t0 = time.perf_counter()
    queries = [q for _, q in COMPARE_ASPECTS]
    src_a = _doc_sources(db, user_id, doc_a, queries, per_query=2, start_id=1)
    src_b = _doc_sources(db, user_id, doc_b, queries, per_query=2, start_id=len(src_a) + 1)
    if not src_a or not src_b:
        raise ValueError("Both documents must be fully indexed before they can be compared.")
    sources = src_a + src_b
    label = {doc_a.id: "Document A", doc_b.id: "Document B"}
    aspects = ", ".join(a for a, _ in COMPARE_ASPECTS)
    prompt = f"""Compare Document A ("{doc_a.filename}") with Document B ("{doc_b.filename}") for these aspects: {aspects}.

SOURCE PASSAGES (each tagged with the document it comes from):
{_format_sources(sources, label, max_chars=36000)}

Return JSON:
{{
  "overview": "3-5 sentence summary of the most important differences",
  "aspects": [
    {{
      "aspect": "aspect name from the list",
      "status": "common" | "different" | "missing_in_a" | "missing_in_b" | "missing_in_both",
      "document_a": {{"summary": "what Document A says (or 'Not found in retrieved passages')", "source_ids": ["S1"]}},
      "document_b": {{"summary": "what Document B says (or 'Not found in retrieved passages')", "source_ids": ["S9"]}},
      "key_differences": "concise description of differences, empty if common",
      "wording_changes": ["significant wording change, quoting both versions briefly"],
      "inconsistencies": ["potential inconsistency or conflict worth reviewing"]
    }}
  ]
}}
Rules: Document A summaries may only cite Document A sources and Document B summaries only Document B sources.
Every factual statement must be backed by source ids. Do not invent content for missing clauses."""
    data = parse_json(get_llm().generate(prompt, system=ANALYST_SYSTEM, json_mode=True))
    a_ids = {s.source_id for s in src_a}
    b_ids = {s.source_id for s in src_b}
    out_aspects = []
    for item in data.get("aspects", []) or []:
        if not isinstance(item, dict):
            continue
        side = {}
        for key, allowed in (("document_a", a_ids), ("document_b", b_ids)):
            part = item.get(key) or {}
            ids = [i for i in _ids(part) if _num(i) in allowed]
            cites = validate_source_ids(ids, sources)
            summary = str(part.get("summary") or "").strip()
            side[key] = {
                "summary": summary if (cites or "not found" in summary.lower()) else
                ("Not verifiable from retrieved passages." if summary else "Not found in retrieved passages."),
                "citations": cites,
            }
        status = str(item.get("status") or "different")
        if status not in {"common", "different", "missing_in_a", "missing_in_b", "missing_in_both"}:
            status = "different"
        out_aspects.append(
            {
                "aspect": str(item.get("aspect") or ""),
                "status": status,
                **side,
                "key_differences": str(item.get("key_differences") or ""),
                "wording_changes": [str(x) for x in (item.get("wording_changes") or []) if x],
                "inconsistencies": [str(x) for x in (item.get("inconsistencies") or []) if x],
            }
        )
    summary_counts = {
        "common": sum(1 for a in out_aspects if a["status"] == "common"),
        "different": sum(1 for a in out_aspects if a["status"] == "different"),
        "missing": sum(1 for a in out_aspects if a["status"].startswith("missing")),
    }
    return {
        "document_a": {"id": doc_a.id, "name": doc_a.filename},
        "document_b": {"id": doc_b.id, "name": doc_b.filename},
        "overview": str(data.get("overview") or ""),
        "aspects": out_aspects,
        "counts": summary_counts,
        "duration_ms": int((time.perf_counter() - t0) * 1000),
        "disclaimer": DISCLAIMER,
    }


# --------------------------------------------------------------------------- summary
LENGTH_GUIDE = {
    "short": "Executive summary of 2-3 sentences; at most 3 items per list.",
    "medium": "Executive summary of one paragraph (4-6 sentences); at most 6 items per list.",
    "detailed": "Executive summary of two paragraphs; include every relevant item (up to 12 per list).",
}

SUMMARY_LISTS = [
    "key_obligations", "financial_obligations", "termination_provisions",
    "liability_conditions", "confidentiality_provisions", "potential_risks",
]


def summarize(db: Session, user_id: str, doc: Document, length: str = "medium") -> dict:
    t0 = time.perf_counter()
    chunks = _all_chunks(db, user_id, doc)
    if not chunks:
        raise ValueError("No indexed text found for this document.")
    total_chars = sum(len(c.text) for c in chunks)
    if total_chars <= 40000:
        sources = [Source(i + 1, c) for i, c in enumerate(chunks)]
        coverage = "full"
    else:  # long document: opening section + passages most relevant to each summary aspect
        sources = [Source(i + 1, c) for i, c in enumerate(chunks[:8])]
        seen = {s.chunk.chunk_id for s in sources}
        for q in SUMMARY_ASPECTS:
            for c in retrieve(db, user_id, q, document_ids=[doc.id], top_k=12, rerank_top_n=4).chunks:
                if c.chunk_id not in seen:
                    seen.add(c.chunk_id)
                    sources.append(Source(len(sources) + 1, c))
        coverage = "partial"

    prompt = f"""Summarise the document "{doc.filename}" using only the source passages.
Length: {LENGTH_GUIDE.get(length, LENGTH_GUIDE['medium'])}

SOURCE PASSAGES:
{_format_sources(sources, max_chars=42000)}

Return JSON:
{{
  "executive_summary": "text",
  "executive_summary_source_ids": ["S1"],
  "parties": [{{"name": "party name", "role": "role in the agreement", "source_ids": ["S1"]}}],
  "important_dates": [{{"date": "date or period exactly as written", "description": "what it refers to", "source_ids": ["S2"]}}],
  {", ".join(f'"{k}": [{{"text": "...", "source_ids": ["S3"]}}]' for k in SUMMARY_LISTS)}
}}
Every list item must cite the source ids it is based on. Use empty lists when the document has nothing relevant."""
    data = parse_json(get_llm().generate(prompt, system=ANALYST_SYSTEM, json_mode=True))
    dropped = 0

    def clean_list(items: Any, fields: tuple[str, ...]) -> list[dict]:
        nonlocal dropped
        out = []
        for it in items or []:
            if not isinstance(it, dict):
                continue
            cites = validate_source_ids(_ids(it), sources)
            if not cites:
                dropped += 1
                continue
            row = {f: str(it.get(f) or "").strip() for f in fields}
            row["citations"] = [
                {k: c[k] for k in ("source_id", "chunk_id", "document_name", "page_number", "text")} for c in cites
            ]
            out.append(row)
        return out

    result = {
        "document_id": doc.id,
        "document_name": doc.filename,
        "length": length,
        "coverage": coverage,
        "executive_summary": str(data.get("executive_summary") or ""),
        "executive_summary_citations": validate_source_ids(data.get("executive_summary_source_ids") or [], sources),
        "parties": clean_list(data.get("parties"), ("name", "role")),
        "important_dates": clean_list(data.get("important_dates"), ("date", "description")),
    }
    for k in SUMMARY_LISTS:
        result[k] = clean_list(data.get(k), ("text",))
    result["unsupported_items_removed"] = dropped
    result["duration_ms"] = int((time.perf_counter() - t0) * 1000)
    result["disclaimer"] = DISCLAIMER
    return result
